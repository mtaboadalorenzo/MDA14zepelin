REALIDAD = {"L": "legítima", "F": "falsa", "S": "sin fundamento"}
NIVEL = {"S": "sencillo", "I": "intermedio", "D": "difícil"}


def r2(x):
    return round(x + 1e-9, 2)


def compensacion_justa(t, total):
    if t["real"] != "L":
        return 0.0
    tipo = t["tipo"]
    if tipo == "no llegó":
        return total
    if tipo == "tarde o frío":
        ret = t["ret"] or 0
        if ret >= 40:
            return r2(total * 0.5)
        if ret >= 20:
            return r2(total * 0.3)
        return 0.0
    for nombre, precio, _ in t["prod"]:
        if nombre == t["af"]:
            return precio
    raise ValueError(f"Producto afectado no encontrado en ZP-{t['id']:03d}")


def main():
    raiz = Path(__file__).resolve().parent.parent
    tickets, verdad = [], {}
    for t in sorted(T, key=lambda x: x["id"]):
        tid = f"ZP-{t['id']:03d}"
        productos = [{"nombre": n, "precio": p, "cantidad": c} for n, p, c in t["prod"]]
        total = r2(sum(p * c for _, p, c in t["prod"]) + ENVIO)
        tickets.append({
            "id": tid,
            "cliente": {"antiguedad_meses": t["ant"], "pedidos_90d": t["ped"], "reclamaciones_90d": t["rec"]},
            "pedido": {"restaurante": t["rest"], "productos": productos, "envio": ENVIO,
                       "total": total, "retraso_min": t["ret"]},
            "entrega": {"tipo": "en mano" if t["ent"] == "mano" else "en la puerta",
                        "gps_confirma": t["gps"], "incidencias_repartidor_mes": t["inc"]},
            "restaurante": {"quejas_mes": QUEJAS_RESTAURANTE[t["rest"]]},
            "incidencia": {"tipo": t["tipo"], "mensaje": t["msg"]},
        })
        assert len(t["msg"]) <= 400, tid
        verdad[tid] = {
            "realidad": REALIDAD[t["real"]],
            "compensacion_justa": compensacion_justa(t, total),
            "producto_afectado": t.get("af"),
            "valor_anual_cliente": r2(t["ped"] * 4 * MARGEN_POR_PEDIDO),
            "gemelo_de": f"ZP-{t['gemelo']:03d}" if t.get("gemelo") else None,
            "se_repite": bool(t.get("rep")),
            "pone_a_prueba": t.get("prueba", ""),
            "nivel": NIVEL[t.get("nivel", "S")],
            "mala_suerte": bool(t.get("mala")),
            "que_paso_despues": t.get("despues"),
        }
    (raiz / "data").mkdir(exist_ok=True)
    (raiz / "data" / "tickets.json").write_text(json.dumps(tickets, ensure_ascii=False, indent=2), encoding="utf-8")
    (raiz / "data" / "verdad.json").write_text(json.dumps(verdad, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"{len(tickets)} tickets generados")


if __name__ == "__main__":
    main()
